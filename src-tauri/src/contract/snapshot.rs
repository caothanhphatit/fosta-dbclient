//! An engine-neutral picture of one schema (or database) for schema compare: tables with their columns, keys, checks,
//! indexes and foreign keys, and views. Engines fill it through [`super::engine::SchemaSnapshotSource`] with a few bulk
//! catalog reads.
//!
//! Snapshots keep the **raw** catalog text (types, defaults, expressions as the server spells them). Normalization
//! happens at diff time through the engine's [`super::migration::SchemaDialect`], so the compare options stay pure and
//! the normalizers are unit-testable. These types are separate from [`super::describe::ObjectDescription`] on purpose:
//! that one is a display DTO.

use serde::{Deserialize, Serialize};

/// What one side of a compare covers: a database, and a schema inside it for engines with schemas.
#[derive(Clone, Debug, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SnapshotScope {
    pub database: String,
    pub schema: Option<String>,
}

impl SnapshotScope {
    pub fn new(database: &str, schema: Option<&str>) -> Self {
        Self {
            database: database.to_owned(),
            schema: schema.map(str::to_owned),
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SchemaSnapshot {
    /// The registry id of the engine (`postgres`, `mariadb`, ...).
    pub engine: String,
    pub server_version: String,
    pub scope: SnapshotScope,
    /// Whether the server folds identifier case (MySQL `lower_case_table_names != 0`, a case-insensitive SQL Server
    /// collation, SQLite).
    pub case_insensitive_names: bool,
    pub tables: Vec<TableDef>,
    pub views: Vec<ViewDef>,
    /// Objects of the scope this version does not compare (triggers, routines, sequences, ...), so the UI can say so.
    pub skipped: Vec<SkippedObject>,
    /// When the catalog was read (RFC 3339).
    pub read_at: String,
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TableDef {
    pub name: String,
    /// In catalog order.
    pub columns: Vec<ColumnDef>,
    pub primary_key: Option<KeyDef>,
    pub uniques: Vec<KeyDef>,
    pub checks: Vec<CheckDef>,
    /// Excludes the indexes backing the primary key and unique constraints.
    pub indexes: Vec<IndexDef>,
    pub foreign_keys: Vec<ForeignKeyDef>,
    pub comment: Option<String>,
    /// Engine options shown for review (`engine`, `charset`, `collation`, `strict`, `withoutRowid`, ...).
    pub options: Vec<(String, String)>,
    /// The engine's own CREATE text where a rebuild needs it (SQLite); optional elsewhere.
    pub native_ddl: Option<String>,
}

impl TableDef {
    pub fn new(name: &str) -> Self {
        Self {
            name: name.to_owned(),
            ..Self::default()
        }
    }
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ColumnDef {
    pub name: String,
    /// The engine's raw spelling of the type.
    pub type_name: String,
    pub nullable: bool,
    /// The raw default expression.
    pub default: Option<String>,
    /// The name of the default's constraint where defaults are constraints (SQL Server `DF_...`).
    pub default_name: Option<String>,
    pub identity: Option<IdentityDef>,
    pub generated: Option<GeneratedDef>,
    pub collation: Option<String>,
    pub comment: Option<String>,
}

impl ColumnDef {
    pub fn new(name: &str, type_name: &str, nullable: bool) -> Self {
        Self {
            name: name.to_owned(),
            type_name: type_name.to_owned(),
            nullable,
            ..Self::default()
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum IdentityKind {
    /// `GENERATED ALWAYS AS IDENTITY`.
    Always,
    /// `GENERATED BY DEFAULT AS IDENTITY`, SQL Server `IDENTITY`.
    ByDefault,
    /// PostgreSQL `serial` (an integer with a `nextval` default).
    Serial,
    /// MySQL `AUTO_INCREMENT`, SQLite `AUTOINCREMENT` / rowid alias.
    AutoIncrement,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct IdentityDef {
    pub kind: IdentityKind,
    pub start: Option<i64>,
    pub increment: Option<i64>,
}

/// A generated (computed) column.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct GeneratedDef {
    pub expression: String,
    /// Stored (persisted) rather than virtual.
    pub stored: bool,
}

/// A primary key or unique constraint.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct KeyDef {
    pub name: Option<String>,
    pub columns: Vec<String>,
    /// The server chose the name (SQL Server `PK__orders__3213E83F`); matched by definition, not by name.
    pub system_named: bool,
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct CheckDef {
    pub name: Option<String>,
    pub expression: String,
    pub system_named: bool,
}

/// One key part of an index: a column or an expression.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct IndexPart {
    pub column: Option<String>,
    pub expression: Option<String>,
    pub descending: bool,
}

impl IndexPart {
    pub fn column(name: &str) -> Self {
        Self {
            column: Some(name.to_owned()),
            ..Self::default()
        }
    }
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct IndexDef {
    pub name: String,
    pub parts: Vec<IndexPart>,
    pub unique: bool,
    /// Access method or index type (`btree`, `gin`, `HASH`, `NONCLUSTERED`, ...).
    pub method: Option<String>,
    /// The predicate of a partial (filtered) index.
    pub predicate: Option<String>,
    /// Covered (`INCLUDE`) columns.
    pub include: Vec<String>,
    pub system_named: bool,
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ForeignKeyDef {
    pub name: Option<String>,
    pub columns: Vec<String>,
    /// The referenced schema; `None` = the scope's own schema.
    pub ref_schema: Option<String>,
    pub ref_table: String,
    pub ref_columns: Vec<String>,
    pub on_update: Option<String>,
    pub on_delete: Option<String>,
    pub system_named: bool,
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ViewDef {
    pub name: String,
    /// The raw body (the `SELECT ...`).
    pub definition: String,
    pub materialized: bool,
    /// Tables and views of the scope the view reads, where the catalog knows.
    pub depends_on: Vec<String>,
    pub comment: Option<String>,
}

/// An object of the scope that is not compared in this version.
#[derive(Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SkippedObject {
    pub kind: String,
    pub name: String,
    pub reason: String,
}
