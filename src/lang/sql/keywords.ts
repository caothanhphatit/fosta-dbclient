/** Words that must be quoted to be used as identifiers (a conservative set shared by all dialects plus extras). */
const RESERVED_COMMON = new Set(
  words(`
    ALL ALTER AND AS ASC BETWEEN BY CASE CHECK COLUMN CONSTRAINT CREATE CROSS DEFAULT DELETE DESC DISTINCT DROP ELSE
    END EXCEPT EXISTS FALSE FOR FOREIGN FROM FULL GRANT GROUP HAVING IN INNER INSERT INTERSECT INTO IS JOIN LEFT LIKE
    LIMIT NATURAL NOT NULL OFFSET ON OR ORDER OUTER PRIMARY REFERENCES REVOKE RIGHT SELECT SET TABLE THEN TO TRUE UNION
    UNIQUE UPDATE USER USING VALUES WHEN WHERE WITH
  `),
);
const RESERVED_EXTRA: Partial<Record<LangDialect, string[]>> = {
  mySql: words("INDEX KEY DATABASE SCHEMA REPLACE INTERVAL RANGE ROWS ROW RANK USE"),
  mariaDb: words("INDEX KEY DATABASE SCHEMA REPLACE INTERVAL RANGE ROWS ROW USE"),
  msSql: words("INDEX KEY TOP DATABASE PROC PROCEDURE FUNCTION VIEW TRIGGER FILE OPEN CLOSE EXEC PERCENT PLAN PUBLIC RULE"),
  postgres: words("ANALYZE ARRAY CAST COLLATE DO FETCH ILIKE LATERAL ONLY RETURNING WINDOW"),
  sqlite: words("INDEX VIEW TRIGGER"),
  oracle: words("INDEX VIEW LEVEL SIZE START MODE COMMENT FILE NUMBER ROWID ROWNUM UID SESSION ACCESS"),
};

export function isReservedWord(dialect: LangDialect, word: string): boolean {
  const upper = word.toUpperCase();
  return RESERVED_COMMON.has(upper) || (RESERVED_EXTRA[dialect]?.includes(upper) ?? false);
}

const cache = new Map<string, string[]>();
const unique = (list: string[]) => [...new Set(list)];

/** Completion keywords of a dialect (upper case). */
export function dialectKeywords(dialect: LangDialect): string[] {
  const key = `k:${dialect}`;
  let list = cache.get(key);
  if (!list) {
    list = unique([...COMMON_KEYWORDS, ...DIALECT_KEYWORDS[dialect]]);
    cache.set(key, list);
  }
  return list;
}

/** Built-in functions of a dialect, in their canonical case (ClickHouse function names are case-sensitive). */
export function dialectFunctions(dialect: LangDialect): string[] {
  const key = `f:${dialect}`;
  let list = cache.get(key);
  if (!list) {
    list = dialect === "clickHouse" ? unique(DIALECT_FUNCTIONS.clickHouse) : unique([...COMMON_FUNCTIONS, ...DIALECT_FUNCTIONS[dialect]]);
    cache.set(key, list);
  }
  return list;
}

export function statementStarters(dialect: LangDialect): string[] {
  const extra: Partial<Record<LangDialect, string[]>> = {
    mySql: ["SHOW", "DESCRIBE", "USE", "REPLACE", "CALL"],
    mariaDb: ["SHOW", "DESCRIBE", "USE", "REPLACE", "CALL"],
    msSql: ["EXEC", "DECLARE", "PRINT", "MERGE", "USE", "IF"],
    postgres: ["VACUUM", "ANALYZE", "COPY", "DO"],
    sqlite: ["PRAGMA", "VACUUM", "ATTACH", "REPLACE"],
    clickHouse: ["OPTIMIZE", "SYSTEM", "DESCRIBE"],
    oracle: ["DECLARE", "MERGE", "CALL"],
  };
  return unique([...STATEMENT_STARTERS, ...(extra[dialect] ?? [])]);
}
