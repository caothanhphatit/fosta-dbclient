-- Schema compare test data (src-tauri/src/contract/testing, suite schema_compare). The suite runs this file before
-- each direction, chunk by chunk (chunks are separated by lines that read GO), so it must be safe to run again.
-- Schemas compare_a and compare_b of database shop differ in the ways the suite expects (see the comments in B).
DROP SCHEMA IF EXISTS compare_a CASCADE;
GO
DROP SCHEMA IF EXISTS compare_b CASCADE;
GO
CREATE SCHEMA compare_a;
GO
CREATE SCHEMA compare_b;
GO
CREATE TYPE compare_a.mood AS ENUM ('happy', 'sad');
GO
CREATE SEQUENCE compare_a.invoice_seq;
GO
CREATE TABLE compare_a.customers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar(200) NOT NULL,
  name varchar(100),
  status varchar(20) NOT NULL DEFAULT 'active',
  mood compare_a.mood,
  CONSTRAINT customers_email_key UNIQUE (email)
);
GO
COMMENT ON TABLE compare_a.customers IS 'Customers of the shop';
GO
CREATE TABLE compare_a.orders (
  id bigserial PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES compare_a.customers (id) ON DELETE CASCADE,
  total numeric(12,2) NOT NULL DEFAULT 0,
  qty bigint NOT NULL,
  note varchar(50),
  placed_at timestamptz NOT NULL DEFAULT now(),
  shipped boolean,
  invoice_no bigint DEFAULT nextval('compare_a.invoice_seq'),
  CONSTRAINT orders_qty_check CHECK (qty > 0)
);
GO
COMMENT ON COLUMN compare_a.orders.total IS 'Including tax';
GO
CREATE INDEX orders_placed_idx ON compare_a.orders (placed_at DESC);
GO
CREATE INDEX orders_open_idx ON compare_a.orders (customer_id) WHERE NOT shipped;
GO
CREATE TABLE compare_a.items (
  order_id bigint NOT NULL REFERENCES compare_a.orders (id),
  sku text NOT NULL,
  price numeric(10,2),
  PRIMARY KEY (order_id, sku)
);
GO
CREATE TABLE compare_a.tags (
  id integer PRIMARY KEY,
  label text NOT NULL,
  color text
);
GO
CREATE TABLE compare_a.a_only (
  id integer PRIMARY KEY,
  label text,
  mood compare_a.mood DEFAULT 'happy'
);
GO
CREATE TABLE compare_a.flyway_schema_history (
  installed_rank integer PRIMARY KEY,
  version varchar(50)
);
GO
CREATE VIEW compare_a.v_customer_orders AS
  SELECT c.id, c.email, count(o.id) AS orders
  FROM compare_a.customers c LEFT JOIN compare_a.orders o ON o.customer_id = c.id
  GROUP BY c.id, c.email;
GO
CREATE VIEW compare_a.v_big_orders AS SELECT id, qty FROM compare_a.orders WHERE qty > 10;
GO
CREATE MATERIALIZED VIEW compare_a.mv_totals AS
  SELECT customer_id, sum(total) AS total FROM compare_a.orders GROUP BY customer_id;
GO
CREATE TYPE compare_b.mood AS ENUM ('happy', 'sad');
GO
CREATE SEQUENCE compare_b.invoice_seq;
GO
-- customers: name narrower, another status default, no unique email, a column A does not have, another comment.
CREATE TABLE compare_b.customers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar(200) NOT NULL,
  name varchar(50),
  status varchar(20) NOT NULL DEFAULT 'new',
  mood compare_b.mood,
  legacy text
);
GO
COMMENT ON TABLE compare_b.customers IS 'Old customers';
GO
-- orders: integer keys, no foreign key, a wider note, a nullable placed_at, no shipped, another check, other indexes.
CREATE TABLE compare_b.orders (
  id serial PRIMARY KEY,
  customer_id integer NOT NULL,
  total numeric(12,2) NOT NULL DEFAULT 0,
  qty integer NOT NULL,
  note varchar(200),
  placed_at timestamptz DEFAULT now(),
  invoice_no bigint DEFAULT nextval('compare_b.invoice_seq'),
  CONSTRAINT orders_qty_check CHECK (qty >= 0)
);
GO
CREATE INDEX orders_note_idx ON compare_b.orders (note);
GO
-- items: its foreign key column follows the type change of orders.id.
CREATE TABLE compare_b.items (
  order_id integer NOT NULL REFERENCES compare_b.orders (id),
  sku text NOT NULL,
  price numeric(10,2),
  PRIMARY KEY (order_id, sku)
);
GO
-- tags: the same columns in another order (identical with the default options).
CREATE TABLE compare_b.tags (
  id integer PRIMARY KEY,
  color text,
  label text NOT NULL
);
GO
CREATE TABLE compare_b.b_only (
  id integer PRIMARY KEY,
  payload jsonb
);
GO
CREATE VIEW compare_b.v_customer_orders AS
  SELECT c.id, count(o.id) AS orders
  FROM compare_b.customers c LEFT JOIN compare_b.orders o ON o.customer_id = c.id
  GROUP BY c.id;
GO
CREATE VIEW compare_b.v_big_orders AS SELECT id, qty FROM compare_b.orders WHERE qty > 10;
GO
CREATE MATERIALIZED VIEW compare_b.mv_totals AS
  SELECT customer_id, sum(total) AS total FROM compare_b.orders GROUP BY customer_id;
